"""Appendix tables of the paper, each written as CSV and as Markdown with the same content.

E_benchmark (every attempted case) and K_freeze (tool freezes), the table type and writer, and the
cost rows of one campaign (cost_rows). The tables of the current-release campaigns and the benchmark
signatures under the final verdicts (D_corpus, F_detection, G_groups, G4, G5, I_sweep, J_cost, M4)
are in numbers_tables_cur.py.

Run line: not run directly; imported by scripts/paper/paper_numbers.py
"""

from __future__ import annotations

import csv
import logging
import os
from dataclasses import dataclass
from typing import Any, List, Mapping, Sequence

from numbers_bench import BenchData, failure, final_verdict, is_spec
from numbers_io import counts, describe
from numbers_main import wall_seconds

logger = logging.getLogger(__name__)

COST_STATUSES = ("confirmed", "flaky", "not-reproduced", "capped", "labelled-legitimate", "incomplete")


@dataclass(frozen=True)
class Table:
    """One appendix table: file stem, Markdown title, column names and rows."""

    name: str
    title: str
    columns: List[str]
    rows: List[List[Any]]


def yes_no(flag: Any) -> str:
    return "yes" if flag else "no"


def benchmark_table(b: BenchData) -> Table:
    rows = []
    for c in b.cases:
        m = c["meta"]
        ok = final_verdict(b, c) == "reproduced"
        reason = ""
        if not ok:
            why = failure(b, c)
            reason = f"{why['verdict']}: {why['reason']}"
            if why["note"]:
                reason += f" (attempt note: {why['note']})"
        rows.append([c["id"], m["kind"], m["url"], m["title"], f"{m['oracle_class']} / {m['subtype']}",
                     m["pre_build"], m["post_build"], c["repro"]["probe"]["type"], yes_no(is_spec(c)), yes_no(ok),
                     reason])
    return Table("E_benchmark", "Attempted benchmark cases and ground-truth reproduction",
                 ["case", "kind", "issue_url", "title", "class_subtype", "pre_build", "post_build", "probe",
                  "spec_probe", "reproduced", "reason_if_not"], rows)


def cost_rows(campaign: str, results: Sequence[Mapping[str, Any]],
              violations: Sequence[Mapping[str, Any]]) -> List[List[Any]]:
    rows = []
    for oracle, kind in sorted({(str(r["oracle"]), str(r["server_kind"])) for r in results}):
        runs = [r for r in results if r["oracle"] == oracle and r["server_kind"] == kind]
        viol = [v for v in violations if v["oracle"] == oracle and v["server_kind"] == kind]
        stats = describe(wall_seconds(runs))
        status = counts(v["status"] for v in viol)
        rows.append([campaign, oracle, kind, len(runs), sum(1 for r in runs if r["status"] != "ok"),
                     stats["mean"], stats["median"], stats["p90"], round(stats["total"] / 3600, 2),
                     sum(int(r.get("candidates") or 0) for r in runs), len(viol)]
                    + [status.get(s, 0) for s in COST_STATUSES])
    return rows


def freeze_table(freezes: Sequence[Mapping[str, Any]]) -> Table:
    rows = [[f["id"], f.get("created", ""), f.get("tree_digest", ""), len(f.get("files") or {}), f.get("note", "")]
            for f in freezes]
    return Table("K_freeze", "Tool freezes (sha256 manifests of scripts/lsptest and scripts/lsp_repro)",
                 ["id", "created", "tree_digest", "files", "note"], rows)


def cell(value: Any) -> str:
    text = "" if value is None else str(value)
    return text.replace("\r", " ").replace("\n", " ")


def markdown(t: Table) -> str:
    lines = [f"# Appendix table {t.name.split('_', 1)[0]}: {t.title}", "",
             f"Generated by scripts/paper/paper_numbers.py; same content as {t.name}.csv ({len(t.rows)} rows).", "",
             "| " + " | ".join(t.columns) + " |", "|" + "---|" * len(t.columns)]
    lines += ["| " + " | ".join(cell(v).replace("|", "\\|") for v in row) + " |" for row in t.rows]
    return "\n".join(lines) + "\n"


def write_tables(tables: Sequence[Table], out_dir: str) -> List[str]:
    """Write <name>.csv and <name>.md for each table; returns the written paths."""
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for t in tables:
        csv_path = os.path.join(out_dir, f"{t.name}.csv")
        with open(csv_path, "w", encoding="utf-8", newline="") as f:
            w = csv.writer(f)
            w.writerow(t.columns)
            w.writerows([[cell(v) for v in row] for row in t.rows])
        md_path = os.path.join(out_dir, f"{t.name}.md")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(markdown(t))
        written += [csv_path, md_path]
        logger.info("table %s: %d rows", t.name, len(t.rows))
    return written


def all_tables(b: BenchData, freezes: Sequence[Mapping[str, Any]]) -> List[Table]:
    """E_benchmark and K_freeze (the other tables come from numbers_tables_cur.cur_tables)."""
    return [benchmark_table(b), freeze_table(freezes)]
