"""Turn data/lsptest/paper_numbers.json into paper/numbers.tex, so that the paper types no number
by hand: every scalar leaf becomes a macro read with \\N{dotted.key}, e.g. \\N{main.triage_groups.total}.
A key that does not exist prints a red marker instead of failing the build, so a renamed key is
visible in the PDF. Null leaves (numbers that wait for the author's judgements) print "pending".

Run line: python3 scripts/paper/numbers_tex.py
"""

from __future__ import annotations

import json
import logging
import os
from typing import Any, Dict, Iterator, Tuple

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SOURCE = os.path.join(REPO, "data", "lsptest", "paper_numbers.json")
TARGET = os.path.join(REPO, "paper", "numbers.tex")
FORBIDDEN = set("{}\\%#")

logger = logging.getLogger(__name__)


def leaves(node: Any, prefix: str = "") -> Iterator[Tuple[str, Any]]:
    """Scalar leaves with dotted keys; lists are skipped (tables carry them)."""
    if isinstance(node, dict):
        for k, v in node.items():
            yield from leaves(v, f"{prefix}.{k}" if prefix else str(k))
    elif not isinstance(node, list):
        yield prefix, node


ONE_DECIMAL = (".intervals.", ".hours_per_bug", "_pct")  # printed as 24.0, not 24, next to values like 45.1


def tex_value(v: Any, key: str = "") -> str:
    if v is None:
        return r"\textcolor{red}{pending}"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float) and any(m in f".{key}" for m in ONE_DECIMAL):
        return f"{v:.1f}"
    if isinstance(v, float):
        return f"{v:.2f}".rstrip("0").rstrip(".") if abs(v) < 1000 else f"{v:,.0f}"
    if isinstance(v, int):
        return f"{v:,}" if abs(v) >= 1000 else str(v)
    text = str(v)
    return "".join("\\" + c if c in "&_$" else c for c in text) if len(text) <= 80 else r"\textcolor{red}{long}"


def render(doc: Dict[str, Any]) -> str:
    lines = ["% Generated by scripts/paper/numbers_tex.py from data/lsptest/paper_numbers.json; do not edit.",
             r"\makeatletter",
             r"\newcommand{\N}[1]{\@ifundefined{num@#1}{\textcolor{red}{[\detokenize{#1}?]}}{\csname num@#1\endcsname}}"]
    n = 0
    for key, value in leaves(doc):
        if not key or FORBIDDEN & set(key) or key.startswith("sources."):
            continue
        lines.append(f"\\expandafter\\def\\csname num@{key}\\endcsname{{{tex_value(value, key)}}}")
        n += 1
    lines.append(r"\makeatother")
    logger.info("%d number macros", n)
    return "\n".join(lines) + "\n"


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    with open(SOURCE, "r", encoding="utf-8") as f:
        doc = json.load(f)
    text = render(doc)
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(TARGET, REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
